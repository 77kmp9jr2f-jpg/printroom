async function browserSession(code) {
  if (!sessionWork) sessionWork = (async () => {
    const r = await fetch('/api/session', { method: 'POST', credentials: 'same-origin', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(code ? { code } : {}), signal: AbortSignal.timeout(5000) });
    const data = await r.json();
    if (!r.ok) {
      if (data.pairingRequired) showPairing(code ? data.error : '');
      throw new Error(data.error ?? 'Could not connect to Print room');
    }
    session = data; pairingRequired = false;
    $('#pairing').hidden = true; $('#workspace').hidden = false; $('.stop-strip').hidden = false;
    requestAnimationFrame(spyNav);
    $('#pair-device').hidden = session.access !== 'localhost' || !session.lanUrl || !session.pairingRequired;

    return session;
  })().finally(() => { sessionWork = null; });
  return sessionWork;
}
async function api(path, body, renewed = false) {
  if (!session || session.expiresAt < Date.now() + 10000) await browserSession();
  const r = await fetch(path, { method: body === undefined ? 'GET' : 'POST', credentials: 'same-origin', cache: 'no-store',
    headers: body === undefined ? {} : { 'Content-Type': 'application/json', 'X-Print-CSRF': session.csrf },
    body: body === undefined ? undefined : JSON.stringify(body), signal: AbortSignal.timeout(path.includes('/cameras/') ? 12000 : 10000) });
  if (r.status === 401 && body === undefined && !renewed) { await browserSession(); return api(path, undefined, true); }
  if (r.status === 401 && session?.access === 'lan' && session.pairingRequired) showPairing('Access expired. Enter a new pairing code from the Print room host.');
  const data = await r.json();
  if (!r.ok) { const e = new Error(data.error ?? `Request failed (${r.status})`); e.status = r.status; throw e; }
  return data;
}
