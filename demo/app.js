async function fingerprint(file) {
  if (!file) return null;
  if (!crypto.subtle) throw new Error('File fingerprinting requires localhost or HTTPS. Enter a SHA-256 calculated on your computer.');
  if (file.size > 100 * 1024 * 1024) throw new Error('For files over 100 MB, calculate SHA-256 locally and enter the filename and hash.');
  const hash = await crypto.subtle.digest('SHA-256', await file.arrayBuffer());
  return { filename: file.name, sha256: [...new Uint8Array(hash)].map(b => b.toString(16).padStart(2, '0')).join('') };
}
