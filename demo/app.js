function gcodePreview(text) {
  let best = null;
  for (const m of text.matchAll(/; thumbnail begin (\d+)x(\d+) \d+\r?\n([\s\S]*?); thumbnail end/g)) {
    const area = Number(m[1]) * Number(m[2]);
    const b64 = m[3].replace(/^; ?/gm, '').replace(/\s+/g, '');
    if (b64 && (!best || area > best.area)) best = { area, b64 };
  }
  return best ? `data:image/png;base64,${best.b64}` : '';
}
function loadJobFacts(card, printer, filename) {
  if (card.metaKey === (filename ?? '') || card.metaRetryAt > Date.now()) return;
  card.metaKey = filename ?? '';
  card.usedAt = 0;
  card.objectMeta.textContent = '';
  card.preview.hidden = true;
  card.preview.removeAttribute('src');
  card.preview.dataset.thumbs = '';
  if (!filename) return;
  api(`/api/v1/printers/${encodeURIComponent(printer.id)}/job-facts`).then(data => {
    const head = data.header ?? '';
    if (card.metaKey !== filename) return;
    const meta = data.result ?? {};
    const tall = Number.isFinite(meta.object_height) ? meta.object_height : Number((head.match(/; max_z_height:\s*([\d.]+)/) || [])[1]);
    const layers = Number((head.match(/; total layer number:\s*(\d+)/) || [])[1]);
    const bits = [];
    if (Number.isFinite(tall)) bits.push(`${measure(tall)} mm tall`);
    if (Number.isFinite(meta.layer_height)) bits.push(`${measure(meta.layer_height)} mm layers`);
    else if (Number.isFinite(meta.first_layer_height)) bits.push(`${measure(meta.first_layer_height)} mm first layer`);
    if (Number.isFinite(layers)) bits.push(`${layers} layers`);
    if (Number.isFinite(meta.nozzle_diameter)) bits.push(`${measure(meta.nozzle_diameter)} mm nozzle`);
    const minx = Number((head.match(/; MINX\s*=\s*([-\d.]+)/i) || [])[1]);
    const maxx = Number((head.match(/; MAXX\s*=\s*([-\d.]+)/i) || [])[1]);
    const miny = Number((head.match(/; MINY\s*=\s*([-\d.]+)/i) || [])[1]);
    const maxy = Number((head.match(/; MAXY\s*=\s*([-\d.]+)/i) || [])[1]);
    if ([minx, maxx, miny, maxy].every(Number.isFinite)) bits.push(`${measure(maxx - minx)} × ${measure(maxy - miny)} mm on bed`);
    const ftype = meta.filament_type || (head.match(/; filament_types?\s*[:=]\s*([^\r\n]+)/i) || [])[1];
    if (ftype) bits.push([...new Set(String(ftype).split(/[,;]/).map(s => s.trim()).filter(Boolean))].join(', '));
    if (Number.isFinite(meta.filament_total)) bits.push(`${measure(meta.filament_total / 1000)} m estimated`);
    if (Number.isFinite(meta.filament_weight_total)) bits.push(`${measure(meta.filament_weight_total)} g filament`);
    if (Number.isFinite(meta.size)) bits.push(`${(meta.size / 1_000_000).toFixed(1)} MB`);
    const generated = (head.match(/; generated by ([^\r\n]+)/) || [])[1];
    const slicer = generated || (meta.slicer && meta.slicer !== 'Unknown' ? [meta.slicer, meta.slicer_version].filter(Boolean).join(' ') : '');
    if (slicer) bits.push(String(slicer).replace(/\s+on .*/, ''));
    card.objectMeta.textContent = bits.join(' · ');
    const src = gcodePreview(head);
    if (src) { card.preview.src = src; return; }
    if (data.preview) card.preview.src = data.preview;
  }).catch(() => { if (card.metaKey === filename) { card.metaKey = null; card.metaRetryAt = Date.now() + 10000; } });
}
